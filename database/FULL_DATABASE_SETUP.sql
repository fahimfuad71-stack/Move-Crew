-- 4. HELPER FUNCTIONS
CREATE OR REPLACE FUNCTION public.is_admin() RETURNS BOOLEAN AS $$ SELECT EXISTS (SELECT 1 FROM public.users WHERE id = auth.uid() AND role = 'admin'); $$ LANGUAGE sql STABLE SECURITY DEFINER;
CREATE OR REPLACE FUNCTION public.is_mover_assigned(p_job_id UUID) RETURNS BOOLEAN AS $$ SELECT EXISTS (SELECT 1 FROM public.assignments WHERE job_id = p_job_id AND mover_id = auth.uid()); $$ LANGUAGE sql STABLE SECURITY DEFINER;

-- 5. POLICIES (Simplified)
CREATE POLICY "Users view own profile" ON public.users FOR SELECT USING (auth.uid() = id OR public.is_admin());
CREATE POLICY "Customer jobs" ON public.jobs FOR ALL USING (customer_id = auth.uid() OR public.is_admin() OR public.is_mover_assigned(id));
CREATE POLICY "Assignment view" ON public.assignments FOR SELECT USING (mover_id = auth.uid() OR public.is_admin());
CREATE POLICY "Location stream" ON public.mover_locations FOR SELECT USING (auth.uid() = mover_id OR public.is_admin() OR EXISTS (SELECT 1 FROM public.assignments a JOIN public.jobs j ON a.job_id = j.id WHERE a.id = mover_locations.assignment_id AND j.customer_id = auth.uid()));
CREATE POLICY "Review access" ON public.reviews FOR SELECT USING (true);
CREATE POLICY "Review insert" ON public.reviews FOR INSERT WITH CHECK (auth.uid() = customer_id);

-- 6. RPCs
CREATE OR REPLACE FUNCTION public.create_move_request(p_pickup_address TEXT, p_destination_address TEXT, p_move_date DATE, p_start_time TIME, p_instructions TEXT, p_items JSONB) RETURNS TABLE (job_id UUID, job_code TEXT) AS $$
DECLARE v_job_id UUID; v_job_code TEXT;
BEGIN
  INSERT INTO public.jobs (customer_id, pickup_address, destination_address, move_date, start_time, instructions, status)
  VALUES (auth.uid(), trim(p_pickup_address), trim(p_destination_address), p_move_date, p_start_time, p_instructions, 'REQUESTED') RETURNING id, jobs.job_code INTO v_job_id, v_job_code;
  INSERT INTO public.job_items (job_id, name, quantity) SELECT v_job_id, trim(item.name), item.quantity FROM jsonb_to_recordset(p_items) AS item(name TEXT, quantity INTEGER);
  RETURN QUERY SELECT v_job_id, v_job_code;
END; $$ LANGUAGE plpgsql SECURITY INVOKER;

CREATE OR REPLACE FUNCTION public.complete_job(p_job_id UUID) RETURNS VOID AS $$ BEGIN UPDATE public.jobs SET status = 'COMPLETED', completed_at = NOW() WHERE id = p_job_id; END; $$ LANGUAGE plpgsql SECURITY DEFINER;

