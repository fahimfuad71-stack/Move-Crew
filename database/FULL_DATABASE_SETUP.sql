-- 1. ENUMS & SEQUENCES
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'user_role') THEN CREATE TYPE public.user_role AS ENUM ('customer', 'admin', 'mover'); END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'job_status') THEN CREATE TYPE public.job_status AS ENUM ('REQUESTED', 'APPROVED', 'ASSIGNED', 'IN_PROGRESS', 'COMPLETED', 'REJECTED', 'CANCELLED'); END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'job_item_status') THEN CREATE TYPE public.job_item_status AS ENUM ('PENDING', 'COLLECTED', 'DELIVERED'); END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'assignment_status') THEN CREATE TYPE public.assignment_status AS ENUM ('PENDING', 'ACCEPTED', 'REJECTED'); END IF;
END $$;

CREATE SEQUENCE IF NOT EXISTS public.job_code_seq START WITH 1001;

-- 2. CORE TABLES
CREATE TABLE IF NOT EXISTS public.users (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name TEXT NOT NULL,
  phone TEXT,
  role public.user_role NOT NULL DEFAULT 'customer',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.customers (id UUID PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS public.movers (id UUID PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE, employee_code TEXT UNIQUE NOT NULL);

CREATE TABLE IF NOT EXISTS public.jobs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  job_code TEXT NOT NULL UNIQUE DEFAULT ('MC-' || LPAD(nextval('public.job_code_seq')::text, 6, '0')),
  customer_id UUID NOT NULL REFERENCES public.customers(id) ON DELETE CASCADE,
  pickup_address TEXT NOT NULL,
  destination_address TEXT NOT NULL,
  move_date DATE NOT NULL,
  start_time TIME NOT NULL,
  instructions TEXT,
  status public.job_status NOT NULL DEFAULT 'REQUESTED',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.job_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id UUID NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  quantity INTEGER NOT NULL DEFAULT 1,
  status public.job_item_status NOT NULL DEFAULT 'PENDING'
);

CREATE TABLE IF NOT EXISTS public.assignments (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  job_id UUID NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
  mover_id UUID NOT NULL REFERENCES public.movers(id) ON DELETE CASCADE,
  status public.assignment_status NOT NULL DEFAULT 'PENDING',
  responded_at TIMESTAMPTZ,
  CONSTRAINT assignments_job_mover_unique UNIQUE (job_id, mover_id)
);

CREATE TABLE IF NOT EXISTS public.mover_locations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  assignment_id UUID NOT NULL REFERENCES public.assignments(id) ON DELETE CASCADE,
  mover_id UUID NOT NULL REFERENCES public.movers(id) ON DELETE CASCADE,
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  accuracy DOUBLE PRECISION,
  recorded_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.time_logs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  assignment_id UUID NOT NULL REFERENCES public.assignments(id) ON DELETE CASCADE,
  mover_id UUID NOT NULL REFERENCES public.movers(id) ON DELETE CASCADE,
  clock_in_at TIMESTAMPTZ,
  clock_out_at TIMESTAMPTZ,
  status TEXT DEFAULT 'ACTIVE'
);

CREATE TABLE IF NOT EXISTS public.reviews (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    job_id UUID NOT NULL REFERENCES public.jobs(id) UNIQUE,
    customer_id UUID NOT NULL REFERENCES public.users(id),
    mover_id UUID NOT NULL REFERENCES public.users(id),
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

